const createInterview = asyncHandler(async(req,res)=>{
    const userId = req.user._id
    const {role,durationInMinutes,difficulty}= req.body


    const resume = await Resume.findOne({userId:req.user._id})

    if(!resume?.resumeAnalysis){
        throw new ApiError(404,"Error in fetching resume")
    }

    const interview = await Interview.create({
        userId:userId,
        role:role,
        durationInMinutes:durationInMinutes,
        difficulty:difficulty,
        status:"Pending",
        startedAt:new Date(),
        endedAt:new Date(Date.now()+durationInMinutes*60*1000),
    })


    if(!interview){
        throw new ApiError(404,"Error while creating Interview");
    }

    const resumeAnalysis= resume.resumeAnalysis

    const generatedQuestions = await generateQuestions({role,durationInMinutes,difficulty,resumeAnalysis})

    if(!generatedQuestions){
        throw new ApiError(400,"Question not generated by AI")
    }

    const questionsToCreate = generatedQuestions.map((question) => ({
        question: question.questionText,
        topic: question.topic,
        questionNo: question.questionNo,
        difficulty: question.difficulty,
        marks: question.marks,
        userId,
        interviewId: interview._id
    }));

    const questions = await Question.insertMany(questionsToCreate);

    return res.status(200).json(new ApiResponse(200,interview,"Interview Created Successfully"))

});



const getAllInterview = asyncHandler(async(req,res)=>{

    const user=req.user;

    const aggregate = await InterviewResult.aggregate([
        {
            $match:{
                userId:user._id
            },

        },
        
        {
            $lookup:{
                from:"interviews",
                localField:"interviewId",
                foreignField : "_id",
                as:"interview"

            }
        },
        {
            $unwind:"$interview"
        },
        {
            $project: {
            marksObtained: 1,
            overallFeedback: 1,
            "interview.role": 1,
            "interview.difficulty": 1,
            "interview.createdAt": 1,
            },
        },
    ])

    return res.status(201).json(new ApiResponse(201,aggregate,"Interview fetched successfully"))
})

const getOneInterview = asyncHandler(async(req,res)=>{
    
    const interview = await Interview.findOne({
        _id:req.params.id,
        userId:req.user._id
    });

    const responses = await Response.find({
        interviewId:req.params.id
    }).populate("questionId");

    const result = await InterviewResult.findOne({
        interviewId:req.params.id
    });

    if(!interview || responses.length===0 || !result){
        throw new ApiError(404,"Error in fetching interview ,response ,question")
    }

    res.status(200).json(new ApiResponse(200,{interview,responses,result},"Successfully fetched interview"))
})


